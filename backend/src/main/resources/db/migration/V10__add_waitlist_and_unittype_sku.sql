-- V10__add_waitlist_and_unittype_sku.sql
-- T1.11 / Task Tx: Bổ sung thuộc tính SKU cho unit_type và tạo bảng waitlist theo mô hình Telesales CRM

-- 1. Bổ sung các thuộc tính SKU mở rộng cho bảng unit_type
ALTER TABLE unit_type ADD COLUMN IF NOT EXISTS pallet_capacity INT DEFAULT 0;
ALTER TABLE unit_type ADD COLUMN IF NOT EXISTS max_load_kg_m2 INT DEFAULT 500;
ALTER TABLE unit_type ADD COLUMN IF NOT EXISTS environment VARCHAR(30) DEFAULT 'DRY';
ALTER TABLE unit_type ADD COLUMN IF NOT EXISTS features VARCHAR(500);

-- 2. Tạo bảng waitlist phục vụ mô hình Telesales CRM (Flow 1, BR-WAT-*)
CREATE TABLE IF NOT EXISTS waitlist (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id             BIGINT NOT NULL,
    facility_id             BIGINT NOT NULL,
    unit_type_id            BIGINT NOT NULL,
    target_start_date       DATE NOT NULL,
    rental_months           INT NOT NULL DEFAULT 1,
    status                  VARCHAR(25) NOT NULL DEFAULT 'WAITING',
    assigned_fm_id          BIGINT NULL,
    last_contacted_at       TIMESTAMP WITH TIME ZONE NULL,
    contact_timeout_at      TIMESTAMP WITH TIME ZONE NULL,
    contact_notes           VARCHAR(500) NULL,
    converted_reservation_id BIGINT NULL,
    converted_contract_id   BIGINT NULL,
    version                 BIGINT NOT NULL DEFAULT 0,
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_waitlist_customer FOREIGN KEY (customer_id) REFERENCES app_user(id),
    CONSTRAINT fk_waitlist_facility FOREIGN KEY (facility_id) REFERENCES facility(id),
    CONSTRAINT fk_waitlist_unit_type FOREIGN KEY (unit_type_id) REFERENCES unit_type(id),
    CONSTRAINT fk_waitlist_assigned_fm FOREIGN KEY (assigned_fm_id) REFERENCES app_user(id),
    CONSTRAINT fk_waitlist_reservation FOREIGN KEY (converted_reservation_id) REFERENCES reservation(id),
    CONSTRAINT fk_waitlist_contract FOREIGN KEY (converted_contract_id) REFERENCES rental_contract(id),
    CONSTRAINT ck_waitlist_status CHECK (status IN ('WAITING', 'CONTACTING', 'PENDING_FOLLOW_UP', 'CONVERTED', 'REJECTED', 'EXPIRED', 'CANCELLED'))
);

-- 3. Tạo Indexes tối ưu hóa tra cứu CRM và quét Scheduled Job
CREATE INDEX IF NOT EXISTS idx_waitlist_lookup ON waitlist (facility_id, unit_type_id, status, created_at);
CREATE INDEX IF NOT EXISTS idx_waitlist_expiry ON waitlist (status, target_start_date);
CREATE INDEX IF NOT EXISTS idx_waitlist_timeout ON waitlist (status, contact_timeout_at);
CREATE INDEX IF NOT EXISTS idx_waitlist_customer ON waitlist (customer_id, status);
CREATE INDEX IF NOT EXISTS idx_waitlist_reservation ON waitlist (converted_reservation_id);
